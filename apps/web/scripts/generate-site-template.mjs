// Generates app/api/genesis/site-template.mjs: every file of the Genesis
// static-site project as a string, for the hosted "download your website" export.
// The Worker has no file system, so the template is embedded at build time.
//
//   node scripts/generate-site-template.mjs           rewrite the module
//   node scripts/generate-site-template.mjs --check   fail if it is stale
//
// tests/site-export.test.mjs fails when the template changes without a rerun.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { getTemplate, templateFiles } from "../../local-control/src/platform/genesis/templates/index.mjs";

export const OUTPUT = new URL("../app/api/genesis/site-template.mjs", import.meta.url);
const TEMPLATE_ID = "static-site";

export function generateSiteTemplateSource() {
  const template = getTemplate(TEMPLATE_ID);
  const files = templateFiles(TEMPLATE_ID)
    .map(({ source, target }) => [target, readFileSync(source, "utf8")])
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
  const lines = files.map(([path, text]) => `  ${JSON.stringify(path)}: ${JSON.stringify(text)},`);
  return `// Generated by scripts/generate-site-template.mjs from
// apps/local-control/src/platform/genesis/templates (the "${TEMPLATE_ID}" template and the shared files it declares).
// Do not edit by hand. Run \`node scripts/generate-site-template.mjs\` after the template changes;
// tests/site-export.test.mjs fails if this copy is stale.
export const SITE_TEMPLATE = ${JSON.stringify({ id: template.id, version: template.version })};
export const SITE_TEMPLATE_FILES = Object.freeze({
${lines.join("\n")}
});
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const next = generateSiteTemplateSource();
  if (process.argv.includes("--check")) {
    let current = "";
    try { current = readFileSync(OUTPUT, "utf8"); } catch { /* missing counts as stale */ }
    if (current !== next) { console.error("site-template.mjs is stale. Run: node scripts/generate-site-template.mjs"); process.exit(1); }
    console.log("site-template.mjs is up to date.");
  } else {
    writeFileSync(OUTPUT, next);
    console.log("Wrote app/api/genesis/site-template.mjs");
  }
}
