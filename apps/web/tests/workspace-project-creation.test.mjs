import assert from "node:assert/strict";
import { register } from "node:module";
import test from "node:test";
import { migratedDatabase } from "./helpers/d1-sqlite.mjs";
import { signSession, sessionCookieHeader } from "../app/api/auth/session.mjs";
import { describeProject } from "../app/chat/project-state.mjs";

register(`data:text/javascript,${encodeURIComponent(`export async function resolve(s,c,n){if(s==='cloudflare:workers')return {url:'data:text/javascript,export const env=globalThis.__workspaceProjectEnv;export class DurableObject {}',shortCircuit:true};return n(s,c);}`)}`, import.meta.url);

test("signed-in workspace owner builds a construction website through chat without deployment-owner access", { timeout: 120000 }, async (t) => {
  const { sqlite, d1 } = migratedDatabase({ users: [[91, "construction-owner"], [92, "other-owner"]] });
  globalThis.__workspaceProjectEnv = { DB: d1 };
  const settings = { ATLAS_SESSION_SECRET: "fixture-session-secret-only", ATLAS_GITHUB_OAUTH_CLIENT_ID: "fixture-client", ATLAS_GITHUB_OAUTH_CLIENT_SECRET: "fixture-oauth-secret", ATLAS_CHAT_BASE_URL: "http://127.0.0.1:11434/v1", ATLAS_CHAT_MODEL: "fixture", ATLAS_CHAT_FALLBACK_MODEL: "none", ATLAS_TRUST_PLATFORM_HEADERS: "false" };
  const previous = Object.fromEntries(Object.keys(settings).map(k => [k, process.env[k]]));
  Object.assign(process.env, settings);
  const originalFetch = globalThis.fetch;
  const calls = [];
  globalThis.fetch = async (_url, options) => {
    const input = JSON.parse(options.body); calls.push(input);
    const tool = input.messages.findLast(m => m.role === "tool");
    const message = tool ? { content: tool.content } : { content: null, tool_calls: [{ id: "create", type: "function", function: { name: "workspace_create_project", arguments: JSON.stringify({ name: "construction-site", description: "Build a construction website.", template: "web-app" }) } }] };
    return Response.json({ choices: [{ message, finish_reason: tool ? "stop" : "tool_calls" }] });
  };
  t.after(() => { globalThis.fetch = originalFetch; delete globalThis.__workspaceProjectEnv; sqlite.close(); for (const [k,v] of Object.entries(previous)) { if(v === undefined) delete process.env[k]; else process.env[k]=v; } });
  const { default: worker } = await import(new URL("../dist/server/index.js", import.meta.url));
  const invoke = (path, init = {}) => worker.fetch(new Request(`http://atlas.test${path}`, init), globalThis.__workspaceProjectEnv, { waitUntil() {}, passThroughOnException() {} });
  const session = async (uid, gh) => ({ cookie: sessionCookieHeader(await signSession({ uid, gh }, settings.ATLAS_SESSION_SECRET)).split(";")[0], "content-type": "application/json" });
  const owner = await session(91, "construction-owner");
  assert.equal((await invoke("/api/genesis/operations", { method: "POST", headers: { "content-type": "application/json" }, body: "{}" })).status, 401);
  assert.equal((await invoke("/api/chat", { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ message: "Build a construction site." }) })).status, 401);
  const signIn = await invoke("/api/auth/github/start");
  assert.ok([302, 303, 307].includes(signIn.status));
  assert.equal(new URL(signIn.headers.get("location")).origin, "https://github.com");
  assert.ok(signIn.headers.get("set-cookie"), "OAuth sign-in issues its state cookie");
  const forged = await invoke("/api/genesis/operations", { method: "POST", headers: { ...owner, "x-atlas-tenant": "999999" }, body: JSON.stringify({ description: "Build a construction website.", template: "static-site" }) });
  assert.ok(forged.status >= 400, "naming a foreign workspace cannot grant creation access");
  assert.equal(sqlite.prepare("SELECT COUNT(*) AS n FROM genesis_projects").get().n, 0);
  const response = await invoke("/api/chat", { method: "POST", headers: owner, body: JSON.stringify({ message: "Build a construction site." }) });
  assert.equal(response.status, 200);
  const result = await response.json();
  const rows = sqlite.prepare("SELECT id, tenant_id, requested_by, status, preview_url FROM genesis_projects").all();
  assert.equal(rows.length, 1, "the actual tool must persist a project despite an irrelevant model template guess");
  assert.equal(rows[0].requested_by, "github:construction-owner");
  assert.equal(rows[0].status, "ready");
  assert.match(result.reply.content, /previewUrl/u);
  assert.equal((await invoke(rows[0].preview_url)).status, 200, "the website workflow produced a renderable preview");
  const other = await session(92, "other-owner");
  const foreign = await invoke(`/api/genesis/operations?id=${rows[0].id}`, { headers: other });
  assert.equal((await foreign.json()).status, "not-found");
  assert.equal((await invoke("/api/genesis/operations", { headers: owner })).status, 403, "workspace ownership never grants access to the deployment node");
  const streamed = await invoke("/api/chat", { method: "POST", headers: owner, body: JSON.stringify({ message: "Build a construction site.", stream: true }) });
  assert.equal(streamed.status, 200);
  const wire = await streamed.text();
  const projects = wire.split("\n\n").filter(block => block.startsWith("event: project\n")).map(block => JSON.parse(block.split("data: ")[1]));
  const completed = projects.find(project => project.status === "ready");
  assert.ok(completed, "streaming frontend receives the actual completed builder state");
  assert.match(completed.previewUrl, /^\/preview\/gen_/u);
  assert.equal((await invoke(completed.previewUrl)).status, 200);
  assert.equal(sqlite.prepare("SELECT COUNT(*) AS n FROM genesis_projects WHERE requested_by = ?").get("github:construction-owner").n, 2);
  assert.ok(calls[0].tools.some(tool => tool.function.name === "workspace_create_project"));
  const deniedCard = describeProject({ status: "unavailable", reason: "owner_required" });
  assert.equal(deniedCard.polling, false);
  assert.match(deniedCard.detail, /could not start/u);
  assert.doesNotMatch(deniedCard.detail, /status updated|review its progress/iu);
});
